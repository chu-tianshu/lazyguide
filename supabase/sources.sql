-- Run once in the Supabase SQL editor, after supabase/catalog.sql. Safe to re-run.
-- Where "search online" looks when a title is not in the cached catalog. Each museum has one or
-- more sources, tried in priority order until one returns a title match. The adapters live in
-- src/lib/sourceSearch/; `kind` picks the adapter and `config` is passed to it.
--
--   cleveland  Cleveland Museum of Art Open Access API (CC0 data, images and texts).
--   aic        Art Institute of Chicago public API (descriptions CC BY 4.0, public-domain images).
--   high       The High Museum's own collection website (WordPress REST API, ~17,000 objects, its gallery
--              text, images only when clearly public domain).
--   wikidata   Wikidata items held in the museum's collection (P195), with the Wikipedia article
--              as text and a Wikimedia Commons image when its licence is public domain / CC0.
--              config: { "collections": ["Q..."] } = the Wikidata items of the museum / its departments.
--              Optional: "idProperty" (a property only this museum's objects carry; one query finds them all),
--              "native" (language of the original titles), "enrich": "louvre" (official record: link + room).
--
-- Public read; written only from the dashboard.

create table if not exists public.museum_sources (
  id integer generated by default as identity primary key,
  museum_id text not null references public.museums (id) on delete cascade,
  kind text not null,
  name text not null,
  url text not null,
  priority integer not null default 0,
  config jsonb not null default '{}',
  unique (museum_id, kind)
);

-- Which adapters exist is code, so the allowed kinds are re-stated here each time this file runs.
alter table public.museum_sources drop constraint if exists museum_sources_kind_check;
alter table public.museum_sources
  add constraint museum_sources_kind_check check (kind in ('cleveland', 'aic', 'high', 'wikidata'));

alter table public.museum_sources enable row level security;
drop policy if exists "public read museum_sources" on public.museum_sources;
create policy "public read museum_sources" on public.museum_sources for select using (true);

grant select on public.museum_sources to anon, authenticated;

-- The search route runs on the server with the service-role key. It reads the sources and
-- stores the works it finds. Those are the only writes to the catalog the app makes.
grant usage on schema public to service_role;
grant select on public.museums, public.catalogs, public.museum_sources to service_role;
grant select, insert on public.works to service_role;
-- New categories found by a search are appended to the catalog's list.
grant update (categories) on public.catalogs to service_role;

